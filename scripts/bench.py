"""Agent-type benchmark (Module 1): reflex vs goal-based vs utility-based on identical scenarios.

    uv run python scripts/bench.py [--random 20] [--seed 1] [--out docs/BENCHMARK.md]

Seeded and deterministic: the same arguments always print the same tables.
"""

import argparse
from pathlib import Path

from resq.agent.baselines import AGENT_KINDS, BenchRow, BenchSummary, benchmark
from resq.world.scenarios import load_all, random_scenario

NAMES = {"reflex": "Simple reflex", "goal": "Goal-based", "utility": "Utility-based (ResQ)"}


def tables(rows: list[BenchRow], summaries: list[BenchSummary], n_random: int, seed: int) -> str:
    out = [
        "# Agent-type benchmark",
        "",
        f"Generated by `make bench` (`--random {n_random} --seed {seed}`). Every number is measured"
        " from a real run; rerunning reproduces it exactly.",
        "",
        "## Summary",
        "",
        "| Agent | Scenarios | Rescued | Rescued % | Mean cost | Mean ticks | Cost per rescue |"
        " Replans |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for s in summaries:
        per = "n/a" if s.cost_per_rescue is None else f"{s.cost_per_rescue:.1f}"
        out.append(
            f"| {NAMES[s.agent]} | {s.scenarios} | {s.rescued}/{s.people} | {s.rescued_pct:.1f}"
            f" | {s.mean_cost:.1f} | {s.mean_ticks:.1f} | {per} | {s.replans} |"
        )
    pct = {s.agent: s.rescued_pct for s in summaries}
    ordered = pct["utility"] >= pct["goal"] >= pct["reflex"]
    out += [
        "",
        f"Ranking by people rescued: utility {pct['utility']:.1f}% , goal-based {pct['goal']:.1f}%"
        f", reflex {pct['reflex']:.1f}%. "
        + (
            "The expected order (utility >= goal >= reflex) holds on average."
            if ordered
            else "The expected order (utility >= goal >= reflex) does NOT hold on this set."
        ),
        "",
        "Reading the columns: the utility agent deliberately rescues the most at-risk person"
        " first, which often costs more path than grabbing the nearest one, so a higher cost"
        ' next to a higher rescue count is the trade-off working, not a defect. "Replans" counts'
        " dropped or replaced plans for the utility agent and changes of destination mid-walk for"
        " the other two.",
        "",
        "## Per scenario (rescued / cost / ticks)",
        "",
        "| Scenario | " + " | ".join(NAMES[k] for k in AGENT_KINDS) + " |",
        "|---|" + "---|" * len(AGENT_KINDS),
    ]
    by: dict[str, dict[str, BenchRow]] = {}
    for r in rows:
        by.setdefault(r.scenario, {})[r.agent] = r
    for name, cells in by.items():
        line = " | ".join(
            f"{c.rescued}/{c.people} · {c.cost:g} · {c.ticks}{'' if c.finished else ' (limit)'}"
            for c in (cells[k] for k in AGENT_KINDS)
        )
        out.append(f"| {name} | {line} |")
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--random", type=int, default=20, help="number of random scenarios")
    parser.add_argument("--seed", type=int, default=1, help="first random-scenario seed")
    parser.add_argument("--out", type=Path, default=None, help="also write the tables here")
    args = parser.parse_args()
    scenarios = [*load_all().values()]
    scenarios += [random_scenario(args.seed + i) for i in range(args.random)]
    rows, summaries = benchmark(scenarios)
    text = tables(rows, summaries, args.random, args.seed)
    print(text)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text)
        print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
